import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { call } from "@orpc/server";
import { describe, expect, it } from "vite-plus/test";

import { createSchoolContext } from "../../testing/school";
import { indexMarkdownDocument } from "../documents/indexing";
import { helpRouter } from "./router";

const GUIDE = join(import.meta.dirname, "../../../../ai/src/school/fixtures/tentang-nemu.md");
const MIGRATIONS_DIR = join(import.meta.dirname, "../../../../db/src/migrations");
const DOC = { id: "tentang-nemu", title: "Tentang Nemu", version: "2026-11" };

const sql = (value: string | number | null | undefined) =>
  value == null
    ? "NULL"
    : typeof value === "number"
      ? `${value}`
      : `'${value.replaceAll("'", "''")}'`;

describe("#305: questions about Nemu itself are answered from Tentang Nemu", () => {
  it.each(["Mikrofon Chrome-nya di mana?", "Apa yang anda ketahui?"])("%s", async (question) => {
    const context = await createSchoolContext();
    const answer = await call(helpRouter.helpAsk, { question }, { context });
    expect(answer.status).toBe("answered");
    if (answer.status !== "answered") return;
    expect(answer.citations[0]).toMatchObject({ docId: DOC.id });
  });

  it("still has no answer for Cuti melahirkan berapa lama? (F3-2 case 5)", async () => {
    const context = await createSchoolContext();
    const answer = await call(
      helpRouter.helpAsk,
      { question: "Cuti melahirkan berapa lama?" },
      { context },
    );
    expect(answer).toEqual({ status: "not_in_guide", answer: "Belum ada di panduan sekolah." });
  });
});

// Regenerate after editing the guide: UPDATE_TENTANG_NEMU_SEED=1 pnpm test
describe("seed_tentang_nemu migration", () => {
  it("seeds the guide exactly as an upload of tentang-nemu.md into Paket AlurSekolah would", async () => {
    const markdown = await readFile(GUIDE, "utf8");
    const chunks = indexMarkdownDocument(DOC, markdown);
    const document = [
      DOC.id,
      "W-SEKOLAH",
      DOC.title,
      DOC.version,
      1,
      "ready",
      "md",
      "tentang-nemu.md",
      "text/markdown",
      new TextEncoder().encode(markdown).byteLength,
      "seed/alursekolah/tentang-nemu.md",
      "[]",
      "alursekolah",
    ].map(sql);
    const rows = chunks.map((chunk) =>
      [
        chunk.id,
        chunk.documentId,
        chunk.article,
        chunk.section,
        chunk.page,
        chunk.sequence,
        chunk.text,
      ]
        .map(sql)
        .join(", "),
    );
    const expected = [
      "-- #305: Tentang Nemu in Paket AlurSekolah, so questions about Nemu itself (the microphone, what",
      '-- Nemu can help with) are answered from a guide instead of "Belum ada di panduan sekolah".',
      "-- Generated by packages/api/src/modules/help/tentang-nemu.test.ts; do not edit by hand.",
      "--> statement-breakpoint",
      `INSERT INTO \`knowledge_document\` (\`id\`, \`workspace_id\`, \`title\`, \`version\`, \`is_active\`, \`status\`, \`format\`, \`file_name\`, \`content_type\`, \`size_bytes\`, \`storage_key\`, \`site_ids\`, \`package_id\`) VALUES (${document.join(", ")});`,
      "--> statement-breakpoint",
      "INSERT INTO `knowledge_chunk` (`id`, `document_id`, `article`, `section`, `page`, `sequence`, `text`) VALUES",
      `${rows.map((row) => `  (${row})`).join(",\n")};`,
      "",
    ].join("\n");

    const folder = (await readdir(MIGRATIONS_DIR)).find((name) =>
      name.endsWith("_seed_tentang_nemu"),
    );
    if (!folder) throw new Error("seed_tentang_nemu migration is missing");
    const path = join(MIGRATIONS_DIR, folder, "migration.sql");
    if (process.env.UPDATE_TENTANG_NEMU_SEED) await writeFile(path, expected);

    expect(await readFile(path, "utf8")).toBe(expected);
  });
});
