import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { describe, expect, it } from "vite-plus/test";

import { DEMO_SEED_DOCUMENTS, DEMO_SEED_INSTANCES } from "./demo-seed";

const MIGRATIONS_DIR = join(import.meta.dirname, "../../../../db/src/migrations");

function sqlValue(value: unknown): string {
  return typeof value === "number" ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
}

function insertStatement(table: string, rows: readonly Record<string, unknown>[]): string {
  const keys = Object.keys(rows[0] ?? {});
  const columns = keys.map((key) => `\`${key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)}\``);
  const values = rows.map((row) => `\t(${keys.map((key) => sqlValue(row[key])).join(", ")})`);
  return `INSERT INTO \`${table}\` (${columns.join(", ")}) VALUES\n${values.join(",\n")};`;
}

// The newest seed migration puts the 3-Momen fixtures in every database, as the demo panel's
// reset does: it deletes the seeded instances (and their documents) and inserts them again.
// Applied migrations stay untouched, so a fixture change needs a new one:
// pnpm --filter @nemu/db db:generate --custom --name=reseed-demo-process-instances
// then fill it with UPDATE_DEMO_SEED=1 pnpm test
describe("reseed-demo-process-instances migration", () => {
  it("seeds exactly the fixtures the demo panel's reset restores", async () => {
    const ids = DEMO_SEED_INSTANCES.map((instance) => sqlValue(instance.id)).join(", ");
    const expected = [
      "-- 3-Momen fixtures for the Demo App: Rina's Perjalanan Dinas in Pertanggungjawaban.",
      "-- Generated by packages/api/src/modules/process-instances/demo-seed.test.ts; do not edit by hand.",
      `DELETE FROM \`process_document\` WHERE \`instance_id\` IN (${ids});`,
      "--> statement-breakpoint",
      `DELETE FROM \`process_instance\` WHERE \`id\` IN (${ids});`,
      "--> statement-breakpoint",
      insertStatement("process_instance", DEMO_SEED_INSTANCES),
      "--> statement-breakpoint",
      insertStatement("process_document", DEMO_SEED_DOCUMENTS),
      "",
    ].join("\n");

    const folder = (await readdir(MIGRATIONS_DIR))
      .filter((name) => name.endsWith("_reseed-demo-process-instances"))
      .sort()
      .at(-1);
    if (!folder) throw new Error("reseed-demo-process-instances migration is missing");
    const path = join(MIGRATIONS_DIR, folder, "migration.sql");
    if (process.env.UPDATE_DEMO_SEED) await writeFile(path, expected);

    expect(await readFile(path, "utf8")).toBe(expected);
  });
});
